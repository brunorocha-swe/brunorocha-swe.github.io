let currentLanguage = "en";
function translate(text) {
  return currentLanguage === "pt-BR" ? (PORTUGUESE[text] ?? text) : text;
}

const translatedNodes = [];
const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
while (walker.nextNode()) {
  const node = walker.currentNode;
  if (node.parentElement.closest("script, style, .language-switch")) continue;
  const original = node.nodeValue;
  if (Object.hasOwn(PORTUGUESE, original.trim())) translatedNodes.push({ node, original });
}
const translatedAttributes = [];
document.querySelectorAll("[aria-label], meta[name='description'], meta[property='og:title'], meta[property='og:description']").forEach(element => {
  const attribute = element.tagName === "META" ? "content" : "aria-label";
  const original = element.getAttribute(attribute);
  if (Object.hasOwn(PORTUGUESE, original)) translatedAttributes.push({ element, attribute, original });
});
const originalTitle = document.title;

function setLanguage(language) {
  currentLanguage = language === "pt-BR" ? "pt-BR" : "en";
  document.documentElement.lang = currentLanguage;
  document.title = translate(originalTitle);
  translatedNodes.forEach(({ node, original }) => {
    node.nodeValue = original.replace(original.trim(), translate(original.trim()));
  });
  translatedAttributes.forEach(({ element, attribute, original }) => element.setAttribute(attribute, translate(original)));
  document.querySelectorAll("[data-language]").forEach(button => {
    button.setAttribute("aria-pressed", String(button.dataset.language === currentLanguage));
  });
  document.querySelectorAll('a[aria-disabled="true"]').forEach(link => link.title = translate("Link not available yet"));
  const menu = document.querySelector(".menu-toggle");
  menu.setAttribute("aria-label", translate(menu.getAttribute("aria-expanded") === "true" ? "Close navigation" : "Open navigation"));
  try { localStorage.setItem("portfolio-language", currentLanguage); } catch { /* Storage may be unavailable for local files. */ }
  document.dispatchEvent(new Event("languagechange"));
}

document.querySelectorAll("[data-language]").forEach(button => button.addEventListener("click", () => setLanguage(button.dataset.language)));
let initialLanguage = "en";
try { initialLanguage = localStorage.getItem("portfolio-language") || "en"; } catch { /* Keep English as the default. */ }
setLanguage(initialLanguage);
